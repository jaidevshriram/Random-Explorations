# Per-shape colour fit. Reads the id render (study.html?probe), keeps the interior
# pixels of each shape, and gives the shape either the reference's mean colour
# over them or, where it clearly helps, a two-colour shade along one axis.
import sys, numpy as np
from PIL import Image
ref = np.asarray(Image.open(sys.argv[1]).convert('RGB')).astype(np.float64); pr = np.asarray(Image.open(sys.argv[2]).convert('RGBA')).astype(np.int64)
ids = (pr[..., 0] << 16) | (pr[..., 1] << 8) | pr[..., 2]; ids[(pr[..., 3] < 255) | (ids > 20000)] = 0
same = np.ones(ids.shape, bool)
for dy in (-1, 0, 1):
    for dx in (-1, 0, 1): same &= (np.roll(np.roll(ids, dy, 0), dx, 1) == ids)
ids = np.where(same, ids, 0); n = int(ids.max()) + 1
ys, xs = np.nonzero(ids); idv = ids[ys, xs]; order = np.argsort(idv, kind='stable'); ys, xs, idv = ys[order], xs[order], idv[order]
starts = np.searchsorted(idv, np.arange(1, n + 1)); hexc = lambda v: '"#%02x%02x%02x"' % tuple(int(np.clip(round(t), 0, 255)) for t in v)
fit, shaded = [], 0
for i in range(1, n):
    a, b = starts[i - 1], starts[i]
    if b - a < 24: fit.append('null'); continue
    col = ref[ys[a:b], xs[a:b]]; mean = col.mean(0); sse0 = ((col - mean) ** 2).sum(); best = None
    if b - a >= 500:
        for axis, pos in ((0, ys[a:b].astype(float)), (1, xs[a:b].astype(float))):
            p0, p1 = pos.min(), pos.max()
            if p1 - p0 < 24: continue
            t = (pos - p0) / (p1 - p0); A = np.stack([1 - t, t], 1); coef, *_ = np.linalg.lstsq(A, col, rcond=None); sse = ((A @ coef - col) ** 2).sum()
            if sse < sse0 * 0.88 and (best is None or sse < best[0]): best = (sse, coef, p0, p1, axis)
    if best: fit.append('[%s,%s,%d,%d,%d]' % (hexc(best[1][0]), hexc(best[1][1]), best[2], best[3], best[4])); shaded += 1
    else: fit.append(hexc(mean))
open(sys.argv[3], 'w').write('// Fitted fills, one per fill call in study.html, in order: a colour, or [from, to, start, end, axis] for a shade. Generated by study-tools/fit.py.\nwindow.STUDY_FIT = [' + ','.join(fit) + '];\n')
print('fitted', sum(f != 'null' for f in fit), 'of', len(fit), 'fills;', shaded, 'shaded')
