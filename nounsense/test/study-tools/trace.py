# Automatic tracing: an adaptive grid of flat-colour squares fitted to the
# reference. Big squares where the picture is flat, small ones along lines.
import sys, numpy as np
from PIL import Image
ref = np.asarray(Image.open(sys.argv[1]).convert('RGB'), dtype=np.float64); H, W = ref.shape[:2]
TOP, MIN = 64, int(sys.argv[3]) if len(sys.argv) > 3 else 2
PH, PW = -(-H // TOP) * TOP, -(-W // TOP) * TOP
pad = np.pad(ref, ((0, PH - H), (0, PW - W), (0, 0)), mode='edge')
def stats(s):   # per-block mean and squared error for block size s
    b = pad.reshape(PH // s, s, PW // s, s, 3); m = b.mean((1, 3)); sse = ((b - m[:, None, :, None, :]) ** 2).sum((1, 3, 4)); return m, sse
def build(thr):
    leaves = []; out = np.zeros_like(pad); s = TOP; alive = np.ones((PH // s, PW // s), bool)
    while True:
        m, sse = stats(s); leaf = alive & ((sse / (s * s * 3) <= thr) | (s == MIN))
        for y, x in zip(*np.nonzero(leaf)): out[y*s:(y+1)*s, x*s:(x+1)*s] = m[y, x]
        leaves.append((s, leaf, m))
        if s == MIN: break
        alive = np.kron(alive & ~leaf, np.ones((2, 2), bool)); s //= 2
    mse = ((out[:H, :W].round() - ref) ** 2).mean(); return leaves, 10 * np.log10(255 ** 2 / mse), sum(int(l.sum()) for _, l, _ in leaves)
if __name__ == '__main__':
    target = float(sys.argv[2]); lo, hi = 0.5, 4000.0
    for _ in range(22):
        mid = (lo * hi) ** 0.5; _, p, n = build(mid)
        if p >= target: lo = mid
        else: hi = mid
    leaves, p, n = build(lo); print(f'min square {MIN}px: {n} squares -> {p:.2f} dB (threshold {lo:.1f})')
    
    if len(sys.argv) > 4:   # write the squares out: one bitmask per size plus colours in raster order
        import base64
        masks, cols = [], []
        for s, leaf, m in leaves:
            masks.append(np.packbits(leaf.ravel()).tobytes()); cols.append(np.clip(m[leaf].round(), 0, 255).astype(np.uint8).tobytes())
        blob = b''.join(masks) + b''.join(cols)
        open(sys.argv[4], 'w').write('// Generated by study-tools/trace.py: an automatic trace of the reference, not a drawing.\nwindow.TRACE = { W: %d, H: %d, PW: %d, PH: %d, top: %d, min: %d, n: %d, data: "%s" };\n' % (W, H, PW, PH, TOP, MIN, n, base64.b64encode(blob).decode()))
        print('wrote', sys.argv[4], round(len(blob) / 1024), 'KB of squares')
